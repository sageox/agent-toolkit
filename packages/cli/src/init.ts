/**
 * The persona is the operator's, not the toolkit's.
 *
 * The toolkit contributes only the two mechanical lines a turn cannot work without;
 * everything about voice, scope, and judgement belongs here, where it can be edited
 * without touching code.
 */
export interface AgentDesign {
  inputs: string;
  success: string;
  boundary: string;
  voice: string;
  metaphor: string;
  palette: string;
  background: string;
  expression: string;
  joke: string;
}

