import { writeFileSync, existsSync, appendFileSync, readFileSync, chmodSync } from "node:fs";

/**
 * Appends a key to `.env` without clobbering an existing one.
 *
 * Overwriting a key that is already there would silently orphan an identity the relay
 * already knows about, so an existing value always wins and is reported instead.
 */
export function upsertEnv(path: string, name: string, value: string): "written" | "kept" {
  const existing = existsSync(path) ? readFileSync(path, "utf8") : "";
  if (new RegExp(`^${name}=`, "m").test(existing)) return "kept";

  const prefix = existing.length && !existing.endsWith("\n") ? "\n" : "";
  appendFileSync(path, `${prefix}${name}=${value}\n`);
  chmodSync(path, 0o600); // it holds a signing key
  return "written";
}

export function writeIfAbsent(path: string, contents: string): "written" | "kept" {
  if (existsSync(path)) return "kept";
  writeFileSync(path, contents);
  return "written";
}

